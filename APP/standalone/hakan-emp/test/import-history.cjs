'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const {DatabaseSync}=require('node:sqlite');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'hakan-import-test-'));
const dbPath=path.join(dir,'IMALAT.db'),json=path.join(dir,'rows.json');
const db=new DatabaseSync(dbPath);
db.exec(`CREATE TABLE companies(id INTEGER PRIMARY KEY,name TEXT,norm TEXT UNIQUE,active INTEGER,opening_balance REAL);
CREATE TABLE models(id INTEGER PRIMARY KEY,name TEXT,norm TEXT UNIQUE,company_id INTEGER);
CREATE TABLE batches(id INTEGER PRIMARY KEY,model_id INTEGER,batch_no TEXT,is_repeat INTEGER,order_no TEXT,ground TEXT,region TEXT,status TEXT,first_date TEXT,last_date TEXT,expected_qty REAL,production_done INTEGER);
CREATE TABLE entries(id INTEGER PRIMARY KEY,batch_id INTEGER,date TEXT,machine_no TEXT,shift TEXT,machine_name TEXT,operator TEXT,assistant TEXT,qty REAL,fabric_defect REAL,print_defect REAL);
CREATE TABLE machines(machine_no TEXT PRIMARY KEY,machine_name TEXT,active INTEGER);`);
db.close();
const row={source_row:2,date:'2024-06-12',model:'DENEME',qty:100,ground:'SİYAH',region:'Ön',machine_no:'No: 2',shift:'Gündüz',machine_name:'MHM',operator:'ALİ',assistant:'',fabric_defect:1,print_defect:2};
fs.writeFileSync(json,JSON.stringify({company:'TAHA GİYİM',rows:[row,{...row,source_row:3}, {...row,source_row:4,date:'2025-05-01',qty:200},{...row,source_row:5,qty:0}]}));
const tool=path.join(__dirname,'..','tools','import-history.cjs');
const run=(apply)=>{const p=spawnSync(process.execPath,[tool,'--db='+dbPath,'--input='+json,...(apply?['--apply']:[])],{encoding:'utf8'});assert.equal(p.status,0,p.stderr||p.stdout);return JSON.parse(p.stdout)};
let r=run(false);assert.equal(r.toInsert,3);assert.equal(r.excluded,1);
r=run(true);assert.equal(r.imported,3);assert.equal(r.finalIntegrity,'ok');
const db2=new DatabaseSync(dbPath);
assert.equal(db2.prepare('SELECT COUNT(*) c FROM entries').get().c,3);
assert.equal(db2.prepare('SELECT COUNT(*) c FROM companies').get().c,1);
assert.equal(db2.prepare('SELECT name FROM companies').get().name,'TAHA GİYİM');
assert.equal(db2.prepare("SELECT COUNT(*) c FROM batches WHERE status='TAMAM'").get().c,2);
db2.close();
r=run(false);assert.equal(r.toInsert,0);
r=run(true);assert.equal(r.imported,0);
fs.rmSync(dir,{recursive:true,force:true});
console.log(JSON.stringify({ok:true,importHistory:true,idempotent:true,years:true,company:'TAHA GİYİM'}));
